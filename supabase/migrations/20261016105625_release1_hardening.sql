  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id text NOT NULL REFERENCES public.campaigns(id),
  ballot_id uuid NOT NULL REFERENCES public.ballots(id) ON DELETE CASCADE,
  invite_id uuid NOT NULL REFERENCES public.invite_codes(id),
  event_type text NOT NULL CHECK (event_type IN ('created','updated')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ballot_audit_campaign ON public.ballot_audit_events(campaign_id,created_at DESC);

