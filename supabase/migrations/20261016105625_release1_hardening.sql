CREATE OR REPLACE FUNCTION public.guard_active_catalog_mutation()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_campaign text;v_status text;v_frozen timestamptz;
BEGIN
  v_campaign:=COALESCE(NEW.campaign_id,OLD.campaign_id);
  SELECT status,results_frozen_at INTO v_status,v_frozen FROM public.campaigns WHERE id=v_campaign;
  IF v_status='open' OR v_frozen IS NOT NULL THEN RAISE EXCEPTION 'CATALOG_LOCKED'; END IF;
  RETURN COALESCE(NEW,OLD);
END;$$;

DROP TRIGGER IF EXISTS trg_guard_menu_categories ON public.menu_categories;
CREATE TRIGGER trg_guard_menu_categories BEFORE UPDATE OR DELETE ON public.menu_categories
FOR EACH ROW EXECUTE FUNCTION public.guard_active_catalog_mutation();

DROP TRIGGER IF EXISTS trg_guard_menu_options ON public.menu_options;
CREATE TRIGGER trg_guard_menu_options BEFORE UPDATE OR DELETE ON public.menu_options
FOR EACH ROW EXECUTE FUNCTION public.guard_active_catalog_mutation();

CREATE OR REPLACE FUNCTION public.submit_ballot(p_campaign_id text,p_token_hash text,p_choices jsonb)
RETURNS TABLE(receipt uuid,saved_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE
  v_status text;v_invite_id uuid;v_expected text[]:=ARRAY['A','B','C','D','E','F','G','H'];
  v_key text;v_selected text;v_valid boolean;v_keycount integer;v_ballot_id uuid;v_saved_at timestamptz;v_event text;
BEGIN
  SELECT status INTO v_status FROM public.campaigns WHERE id=p_campaign_id FOR SHARE;
  IF v_status IS DISTINCT FROM 'open' THEN RAISE EXCEPTION 'VOTING_CLOSED'; END IF;

  SELECT id INTO v_invite_id FROM public.invite_codes
  WHERE campaign_id=p_campaign_id AND token_hash=p_token_hash AND active=true FOR UPDATE;
  IF v_invite_id IS NULL THEN RAISE EXCEPTION 'INVALID_INVITE'; END IF;

  IF p_choices IS NULL OR jsonb_typeof(p_choices)<>'object' THEN RAISE EXCEPTION 'INVALID_BALLOT_SHAPE'; END IF;
  SELECT count(*) INTO v_keycount FROM jsonb_object_keys(p_choices);
  IF v_keycount<>8 THEN RAISE EXCEPTION 'INVALID_BALLOT_SHAPE'; END IF;

  FOREACH v_key IN ARRAY v_expected LOOP
    v_selected:=p_choices->>v_key;
    IF v_selected IS NULL THEN RAISE EXCEPTION 'MISSING_CATEGORY: %',v_key; END IF;
    SELECT EXISTS(
      SELECT 1 FROM public.menu_options
      WHERE campaign_id=p_campaign_id AND category_key=v_key AND id=v_selected
        AND availability_status<>'unavailable'
    ) INTO v_valid;
    IF NOT v_valid THEN RAISE EXCEPTION 'INVALID_MENU_OPTION: %',v_key; END IF;
  END LOOP;

  IF EXISTS(
    SELECT 1 FROM jsonb_object_keys(p_choices) AS t(category_key)
    WHERE t.category_key<>ALL(v_expected)
  ) THEN RAISE EXCEPTION 'UNKNOWN_CATEGORY'; END IF;

  IF EXISTS(SELECT 1 FROM public.ballots WHERE invite_id=v_invite_id) THEN v_event:='updated'; ELSE v_event:='created'; END IF;

  INSERT INTO public.ballots(invite_id,campaign_id,choices) VALUES(v_invite_id,p_campaign_id,p_choices)
  ON CONFLICT(invite_id) DO UPDATE SET choices=EXCLUDED.choices,updated_at=now()
  RETURNING id,updated_at INTO v_ballot_id,v_saved_at;

  INSERT INTO public.ballot_audit_events(campaign_id,ballot_id,invite_id,event_type)
  VALUES(p_campaign_id,v_ballot_id,v_invite_id,v_event);

  RETURN QUERY SELECT v_ballot_id,v_saved_at;
END;$$;

REVOKE ALL ON FUNCTION public.submit_ballot(text,text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.submit_ballot(text,text,jsonb) TO service_role;
